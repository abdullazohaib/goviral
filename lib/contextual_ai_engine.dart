/// Phase 19: Host Speech Intent Categories
enum HostSpeechIntent {
  greeting,
  question,
  productShowcase,
  hypeAndEnergy,
  callForReactions,
  farewell,
  taskRequest,
  friendOrGuest,
  generalChatter,
}

/// Types of floating reaction bursts triggered by the AI audience
enum ReactionBurstType {
  heartShower,
  fireBurst,
  applauseClap,
  sparkles,
}

/// A structured reaction burst event emitted to the live room UI
class ReactionBurstEvent {
  final ReactionBurstType type;
  final int count;
  final Color primaryColor;
  final String triggerReason;
  final DateTime timestamp;

  const ReactionBurstEvent({
    required this.type,
    required this.count,
    required this.primaryColor,
    required this.triggerReason,
    required this.timestamp,
  });
}

/// A multimodal contextual response generated by the AI audience engine
class ContextualAiResponse {
  final AiViewerProfile primaryProfile;
  final String primaryComment;
  final HostSpeechIntent detectedIntent;
  final AiViewerProfile? banterProfile;
  final String? banterComment;
  final ReactionBurstEvent? reactionBurst;

  const ContextualAiResponse({
    required this.primaryProfile,
    required this.primaryComment,
    required this.detectedIntent,
    this.banterProfile,
    this.banterComment,
    this.reactionBurst,
  });
}

/// Phase 19: Multimodal Contextual AI Comments & Reactions Engine
/// Combines Host Speech Understanding (Phase 17) and Video-Frame Understanding (Phase 18)
/// to generate natural, persona-aligned conversational comments, multi-turn audience banter,
/// and automated floating reaction bursts without storing or persisting any user data
/// (fulfills Zero-Persistence Section 1.7).
class ContextualAiEngine extends ChangeNotifier {
  static final ContextualAiEngine instance = ContextualAiEngine._();
  ContextualAiEngine._();

  final Random _random = Random();
  bool _isActive = false;

  void Function(ReactionBurstEvent event)? _onReactionBurst;

  // Recent interaction context (ephemeral, zero persistence)
  DateTime _lastReactionBurstTime = DateTime.fromMillisecondsSinceEpoch(0);
  HostSpeechIntent _lastDetectedIntent = HostSpeechIntent.generalChatter;

  bool get isActive => _isActive;
  HostSpeechIntent get lastDetectedIntent => _lastDetectedIntent;

  /// Starts the contextual AI engine session
  void startSession({void Function(ReactionBurstEvent event)? onReactionBurst}) {
    _isActive = true;
    _onReactionBurst = onReactionBurst;
    _lastReactionBurstTime = DateTime.fromMillisecondsSinceEpoch(0);
    _lastDetectedIntent = HostSpeechIntent.generalChatter;
    notifyListeners();
  }

  /// Classifies spoken host transcript into an intent category across all 8 Indian languages
  HostSpeechIntent classifySpeechIntent(String speech) {
    final lower = speech.toLowerCase().trim();

    // 1. Task / Challenge / Dare requests from host or audience
    final taskRegex = RegExp(
      r'(\b(task|challenge|dare|kya karu|kya karun|koi kaam|kaam batao|give me a task|kuch bolo|batao kya karu|bore|kya challenge|en madodu|yenu madodu|task kodi|enna panlam|task sollunga|em cheddam|task ivvandi|enthu cheyyam|task tharo)\b|क्या करूँ|काम बताओ|టాస్క్|டாஸ்க்|ಟಾಸ್ಕ್|ടാസ്ക്)',
      caseSensitive: false,
    );
    if (taskRegex.hasMatch(lower)) {
      return HostSpeechIntent.taskRequest;
    }

    // 2. Greetings & Welcome
    final greetingRegex = RegExp(
      r'(\b(hello|hi|hey|namaste|kem cho|vanakkam|aadab|welcome|salaam|namaskara|hegidira|namaskaram|bagunnara|sukhamano)\b|नमस्ते|प्रणाम|నమస్కారం|வணக்கம்|ನಮಸ್ಕಾರ|നമസ്കാരം|السلام علیکم|آداب)',
      caseSensitive: false,
    );
    if (greetingRegex.hasMatch(lower)) {
      return HostSpeechIntent.greeting;
    }

    // 3. Call for Reactions / Hearts / Likes
    final reactionRegex = RegExp(
      r'(\b(heart|hearts|dil|like|likes|love|support|pyar|react|thumbs up|tap|hrudaya|anbu|prema|sneham|mohabbat)\b|दिल|प्यार|గుండె|லைக்|ಲೈಕ್|ഹാർട്ട്)',
      caseSensitive: false,
    );
    if (reactionRegex.hasMatch(lower)) {
      return HostSpeechIntent.callForReactions;
    }

    // 4. Friends, guests, or persons in background
    final friendRegex = RegExp(
      r'(\b(dost|friend|friends|partner|guest|brother|peeche|kaun hai|ye mera|yeh mera|milwao|meet|introducing|squad|geleya|snehitha|nanban|pinnaadi|mithrudu|venuka|changathi|aliya|piche)\b|दोस्त|पीछे|நண்பன்|స్నేహితుడు|دوست)',
      caseSensitive: false,
    );
    if (friendRegex.hasMatch(lower)) {
      return HostSpeechIntent.friendOrGuest;
    }

    // 5. Farewells & Wrap-up
    final farewellRegex = RegExp(
      r'(\b(bye|goodbye|see you|alvida|tata|phir milenge|good night|ending|wrap up|matte sigona|poittu varen|varaen|vellivasta|mallikaldam|poittu varam|pinne kaanam|khuda hafiz|shab bakhair)\b|अलविदा|फिर मिलेंगे|போயிட்டு வரேன்|వెళ్లివస్తా|പോയിട്ട് വരാം|خدا حافظ)',
      caseSensitive: false,
    );
    if (farewellRegex.hasMatch(lower)) {
      return HostSpeechIntent.farewell;
    }

    // 6. Product / Item Showcase & Visual Demos
    final productRegex = RegExp(
      r'(\b(look at|dekho|check this|unboxing|phone|camera|t-shirt|watch|setup|screen|specs|product|item|nodi|paarunga|chudandi|nokku)\b|देखो|நோக்கு|చూడండి|ನೋಡಿ)',
      caseSensitive: false,
    );
    if (productRegex.hasMatch(lower)) {
      return HostSpeechIntent.productShowcase;
    }

    // 7. Hype & High Energy
    final hypeRegex = RegExp(
      r"(\b(fire|machaenge|macha diya|let's go|lets go|ready|excited|op|dhamaka|banger|boom|benki|chindi|semma|mass|thee|vera level|keka|rachha|adurs|thopu|adipoli|poli|kiduve|zabardast|kamaal)\b|आग|மசா|రచ్చ|പൊളി|زبردست)",
      caseSensitive: false,
    );
    if (hypeRegex.hasMatch(lower)) {
      return HostSpeechIntent.hypeAndEnergy;
    }

    // 8. Questions & Inquiries
    final questionRegex = RegExp(
      r'(\?|\b(kaisa|kaise|how|what|where|kahan|hear|aawaaz|awaz|audio|clear|guess|batayein|batao|which|hege|elli|eppadi|enga|ela|ekkada|enganeyundu|evide)\b|कैसा|कहाँ|எப்படி|ఎలా|എങ്ങനെ)',
      caseSensitive: false,
    );
    if (questionRegex.hasMatch(lower)) {
      return HostSpeechIntent.question;
    }

    return HostSpeechIntent.generalChatter;
  }

  /// Generates a rich, persona-aligned contextual response to host speech
  ContextualAiResponse generateSpeechResponse({
    required String hostSpeech,
    VisionEvent? recentVisionEvent,
    String streamLanguage = 'Hinglish',
  }) {
    final intent = classifySpeechIntent(hostSpeech);
    _lastDetectedIntent = intent;

    // 1. Select personas matching intent archetype and stream language
    final selectedProfiles = _selectProfilesForIntent(intent, streamLanguage: streamLanguage);
    final primaryProfile = selectedProfiles.primary;
    final banterProfile = selectedProfiles.banter;

    // 2. Synthesize primary contextual comment
    final primaryComment = _synthesizeComment(
      intent: intent,
      profile: primaryProfile,
      hostSpeech: hostSpeech,
      recentVisionEvent: recentVisionEvent,
      streamLanguage: streamLanguage,
    );

    // 3. Synthesize natural audience banter (multi-turn follow up)
    String? banterComment;
    if (banterProfile != null) {
      banterComment = _synthesizeBanterComment(
        intent: intent,
        primaryProfile: primaryProfile,
        banterProfile: banterProfile,
        streamLanguage: streamLanguage,
      );
    }

    // 4. Trigger contextual floating reaction bursts when appropriate
    ReactionBurstEvent? reactionBurst;
    final now = DateTime.now();
    final canBurst = now.difference(_lastReactionBurstTime).inSeconds >= 4;

    if (canBurst) {
      if (intent == HostSpeechIntent.callForReactions) {
        reactionBurst = ReactionBurstEvent(
          type: ReactionBurstType.heartShower,
          count: 8,
          primaryColor: const Color(0xFFFF3D8D), // gvPink
          triggerReason: 'Audience responding with love and hearts!',
          timestamp: now,
        );
      } else if (intent == HostSpeechIntent.hypeAndEnergy) {
        reactionBurst = ReactionBurstEvent(
          type: ReactionBurstType.fireBurst,
          count: 6,
          primaryColor: const Color(0xFFFFA502), // flame amber
          triggerReason: 'High energy hype in the live room!',
          timestamp: now,
        );
      } else if (recentVisionEvent?.type == VisionEventType.highMotion) {
        reactionBurst = ReactionBurstEvent(
          type: ReactionBurstType.sparkles,
          count: 5,
          primaryColor: const Color(0xFF8758FF), // gvPurple
          triggerReason: 'Dynamic visual movement celebration!',
          timestamp: now,
        );
      }

      if (reactionBurst != null) {
        _lastReactionBurstTime = now;
        _onReactionBurst?.call(reactionBurst);
      }
    }

    return ContextualAiResponse(
      primaryProfile: primaryProfile,
      primaryComment: primaryComment,
      detectedIntent: intent,
      banterProfile: banterProfile,
      banterComment: banterComment,
      reactionBurst: reactionBurst,
    );
  }

  /// Generates a contextual reaction when a visual frame cue is observed
  ContextualAiResponse generateVisualResponse({
    required VisionEvent visualEvent,
    String streamLanguage = 'Hinglish',
  }) {
    final emission = AiAudienceCatalog.sampleVisualReaction(
      eventType: visualEvent.type,
      streamLanguage: streamLanguage,
    );


    // Trigger reaction bursts for high energy visual motion or friend entering
    ReactionBurstEvent? reactionBurst;
    final now = DateTime.now();
    if ((visualEvent.type == VisionEventType.highMotion ||
            visualEvent.type == VisionEventType.personEntered) &&
        now.difference(_lastReactionBurstTime).inSeconds >= 4) {
      reactionBurst = ReactionBurstEvent(
        type: visualEvent.type == VisionEventType.personEntered
            ? ReactionBurstType.sparkles
            : ReactionBurstType.fireBurst,
        count: 7,
        primaryColor: visualEvent.type == VisionEventType.personEntered
            ? const Color(0xFFFF3D8D) // gvPink
            : const Color(0xFFFF4757),
        triggerReason: visualEvent.type == VisionEventType.personEntered
            ? 'Someone entered frame in the live room!'
            : 'Host waving / high energy motion detected!',
        timestamp: now,
      );
      _lastReactionBurstTime = now;
      _onReactionBurst?.call(reactionBurst);
    }

    // Banter profile from another city reacting to the visual
    AiViewerProfile? banterProfile;
    String? banterComment;

    final otherProfiles = AiAudienceCatalog.profiles
        .where((p) => p.id != emission.profile.id)
        .toList();
    if (otherProfiles.isNotEmpty) {
      banterProfile = otherProfiles[_random.nextInt(otherProfiles.length)];
      banterComment = _synthesizeVisualBanter(
        primaryName: emission.profile.name,
        type: visualEvent.type,
        streamLanguage: streamLanguage,
      );
    }

    return ContextualAiResponse(
      primaryProfile: emission.profile,
      primaryComment: emission.message,
      detectedIntent: visualEvent.type == VisionEventType.personEntered
          ? HostSpeechIntent.friendOrGuest
          : (visualEvent.type == VisionEventType.closeUpFocus
              ? HostSpeechIntent.productShowcase
              : (visualEvent.type == VisionEventType.highMotion
                  ? HostSpeechIntent.hypeAndEnergy
                  : HostSpeechIntent.generalChatter)),
      banterProfile: banterProfile,
      banterComment: banterComment,
      reactionBurst: reactionBurst,
    );
  }

  _SelectedProfiles _selectProfilesForIntent(
    HostSpeechIntent intent, {
    String? streamLanguage,
  }) {
    List<AiViewerProfile> pool = AiAudienceCatalog.profiles;
    if (streamLanguage != null && streamLanguage.isNotEmpty) {
      final langKey = _resolveLanguageKey(streamLanguage);
      final langMatched = pool.where((p) => p.preferredLanguage.toLowerCase().contains(langKey)).toList();
      if (langMatched.isNotEmpty) {
        pool = langMatched;
      }
    }

    switch (intent) {
      case HostSpeechIntent.taskRequest:
        final pranksters = pool.where((p) =>
            p.archetype.contains('Jokester') ||
            p.archetype.contains('Hype') ||
            p.archetype.contains('Trendsetter')).toList();
        final primary = pranksters.isNotEmpty ? pranksters[_random.nextInt(pranksters.length)] : pool[0];
        final banter = AiAudienceCatalog.profiles.firstWhere((p) => p.id != primary.id);
        return _SelectedProfiles(primary, banter);

      case HostSpeechIntent.friendOrGuest:
        final warm = pool.where((p) =>
            p.archetype.contains('Warm') ||
            p.archetype.contains('Hype') ||
            p.archetype.contains('Culture') ||
            p.archetype.contains('Creative')).toList();
        final primary = warm.isNotEmpty ? warm[_random.nextInt(warm.length)] : pool[0];
        final banter = AiAudienceCatalog.profiles.firstWhere((p) => p.id != primary.id);
        return _SelectedProfiles(primary, banter);

      case HostSpeechIntent.productShowcase:
        final techies = pool.where((p) =>
            p.archetype.contains('Techie') ||
            p.archetype.contains('Analytical') ||
            p.archetype.contains('Trendsetter')).toList();
        final primary = techies.isNotEmpty ? techies[_random.nextInt(techies.length)] : pool[0];
        final banter = AiAudienceCatalog.profiles.firstWhere((p) => p.id != primary.id);
        return _SelectedProfiles(primary, banter);

      case HostSpeechIntent.callForReactions:
        final supporters = pool.where((p) =>
            p.archetype.contains('Enthusiastic') ||
            p.archetype.contains('Warm') ||
            p.archetype.contains('Creative')).toList();
        final primary = supporters.isNotEmpty ? supporters[_random.nextInt(supporters.length)] : pool[0];
        final banter = AiAudienceCatalog.profiles.firstWhere((p) => p.id != primary.id);
        return _SelectedProfiles(primary, banter);

      case HostSpeechIntent.hypeAndEnergy:
        final hype = pool.where((p) =>
            p.archetype.contains('Trendsetter') ||
            p.archetype.contains('Jokester') ||
            p.archetype.contains('Hype')).toList();
        final primary = hype.isNotEmpty ? hype[_random.nextInt(hype.length)] : pool[0];
        final banter = AiAudienceCatalog.profiles.firstWhere((p) => p.id != primary.id);
        return _SelectedProfiles(primary, banter);

      case HostSpeechIntent.greeting:
      case HostSpeechIntent.question:
      case HostSpeechIntent.farewell:
      case HostSpeechIntent.generalChatter:
        final primary = pool[_random.nextInt(pool.length)];
        final otherCandidates = AiAudienceCatalog.profiles.where((p) => p.id != primary.id).toList();
        final banter = otherCandidates[_random.nextInt(otherCandidates.length)];
        return _SelectedProfiles(primary, banter);
    }
  }

  static String _resolveLanguageKey(String streamLanguage) {
    final l = streamLanguage.toLowerCase();
    if (l.contains('hinglish')) return 'hinglish';
    if (l.contains('hindi')) return 'hindi';
    return 'english';
  }

