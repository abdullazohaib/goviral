          : const Color(0xFFFF3D8D),
      triggerReason: 'Simulated reaction burst',
      timestamp: DateTime.now(),
    );
    _lastReactionBurstTime = DateTime.now();
    _onReactionBurst?.call(event);
  }

  /// Cleans up state and frees memory (zero-persistence compliance)
  void stopSession() {
    _isActive = false;
    _onReactionBurst = null;
    _lastReactionBurstTime = DateTime.fromMillisecondsSinceEpoch(0);
    _lastDetectedIntent = HostSpeechIntent.generalChatter;
    notifyListeners();
  }
}

